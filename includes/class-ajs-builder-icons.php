	/**
	 * Inline SVG for a module type, with a letter fallback handled by CSS.
	 *
	 * @param string $type  Widget type.
	 * @param string $class Extra class.
	 * @return string
	 */
	public static function module_svg( $type, $class = '' ) {
		$icons = self::module_icons();
		if ( ! isset( $icons[ $type ] ) ) {
			return '';
		}
		$class = trim( 'ajs-modico ' . $class );
		return '<svg class="' . esc_attr( $class ) . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . $icons[ $type ] . '</svg>';
	}
